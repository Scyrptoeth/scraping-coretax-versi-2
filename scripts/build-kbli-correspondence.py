"""Build five-digit KBLI links from appendices 5 and 10 of BPS publication 03100.26007.

Download the PDF from the publication page linked in extension/kbli-correspondence.js.
Run python3 scripts/build-kbli-correspondence.py <published-pdf> [--output <file>].
Requires PyMuPDF, also used by scripts/build-kbli.py.
"""

import argparse
import hashlib
import json
import re
from pathlib import Path

import fitz

ROOT = Path(__file__).resolve().parents[1]


def read_codes(words, header):
    # The PDF centres numeric codes under the (1) and (3) table headers.
    center = (header[0] + header[2]) / 2
    return sorted((word[1], word[4]) for word in words
                  if word[1] > header[3] and re.fullmatch(r"[0-9]{5}", word[4])
                  and abs((word[0] + word[2]) / 2 - center) < 7)


def read_appendix(doc, appendix, editions, printed_range):
    heading = f"Lampiran {appendix} Tabel Konversi Kelompok KBLI {editions}"
    first = next(i for i, page in enumerate(doc)
                 if heading in [line.strip() for line in page.get_text().splitlines()])
    pairs = {}
    for offset, printed_page in enumerate(range(printed_range[0], printed_range[1] + 1)):
        page = doc[first + offset]
        words = page.get_text("words")
        footer = [w[4] for w in words if w[1] > page.rect.height - 55 and w[4].isdecimal()]
        if footer != [str(printed_page)]:
            raise ValueError(f"Appendix {appendix}: unexpected page number at {printed_page}")
        columns = []
        for label in ["(1)", "(3)"]:
            headers = [w for w in words if w[4] == label]
            if len(headers) != 1:
                raise ValueError(f"Missing or ambiguous column {label} on page {printed_page}")
            columns.append(read_codes(words, headers[0]))
        if not columns[0] or len(columns[0]) != len(columns[1]):
            raise ValueError(f"Incomplete code columns on page {printed_page}")
        for (left_y, left), (right_y, right) in zip(*columns):
            if abs(left_y - right_y) > 1 or (left, right) in pairs:
                raise ValueError(f"Misaligned or duplicate pair on page {printed_page}: {left} {right}")
            pairs[left, right] = printed_page
    return pairs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("pdf", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "extension/kbli-correspondence-data.js")
    args = parser.parse_args()
    with fitz.open(args.pdf) as doc:
        forward = read_appendix(doc, 5, "2020—2025", (117, 231))
        reverse = read_appendix(doc, 10, "2025—2020", (311, 428))
    if len(forward) != 2560 or set(forward) != {(old, new) for new, old in reverse}:
        raise ValueError("The two BPS appendices must independently agree on all 2,560 pairs")
    catalog_file = (ROOT / "extension/catalog-data.js").read_text()
    catalog = json.loads(catalog_file.split("export const kbli = ", 1)[1].strip().removesuffix(";"))
    for year, data in [("2020", forward), ("2025", reverse)]:
        codes = {key for key in catalog[year] if len(key) == 5}
        if {source for source, target in data} != codes:
            raise ValueError(f"Appendix does not cover the same {year} groups as the BPS regulation")
    digest = hashlib.sha256(args.pdf.read_bytes()).hexdigest()
    lines = [f"{old} {new} {forward[old, new]} {reverse[new, old]}" for old, new in sorted(forward)]
    args.output.write_text("// BPS 03100.26007, appendices 5 and 10. Generated by scripts/build-kbli-correspondence.py.\n"
                           f"// Source PDF SHA-256: {digest}\n"
                           "// Columns: KBLI 2020, KBLI 2025, printed page in appendix 5, printed page in appendix 10.\n"
                           "export const groupLinks = `" + "\n".join(lines) + "`;\n")
    print(f"{len(lines)} pairs, verified in both appendices and against both catalogues.")


if __name__ == "__main__":
    main()
